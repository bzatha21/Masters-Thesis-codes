fixed_range <- function(x, pad_frac = 0.04, include_zero = FALSE, symmetric = FALSE) {
  x <- x[is.finite(x)]
  if (length(x) == 0L) return(NULL)
  if (symmetric) {
    m <- max(abs(x), na.rm = TRUE)
    if (!is.finite(m) || m == 0) m <- 1e-6
    return(c(-1, 1) * m * (1 + pad_frac))
  }
  lo <- min(x, na.rm = TRUE)
  hi <- max(x, na.rm = TRUE)
  if (isTRUE(include_zero)) lo <- min(lo, 0)
  if (!is.finite(lo) || !is.finite(hi)) return(NULL)
  if (abs(hi - lo) < 1e-12) {
    pad <- max(abs(hi), 1e-6) * pad_frac
  } else {
    pad <- (hi - lo) * pad_frac
  }
  c(lo - pad, hi + pad)
}

