# Black--Scholes/Lewis control: the Lewis implementation must reproduce
# known B&S prices before it is used for rough Heston recovery.
run_black_lewis_sanity <- function(panel) {
  maturity_rows <- panel %>%
    distinct(tau_days, tau, F, D) %>%
    arrange(tau_days)

  test_rows <- tidyr::expand_grid(
    maturity_rows,
    k_test = c(-0.10, 0.00, 0.10)
  )

  sigma_test <- 0.22

  details <- lapply(seq_len(nrow(test_rows)), function(i) {
    td <- test_rows$tau_days[i]
    Tval <- test_rows$tau[i]
    Fval <- test_rows$F[i]
    Dval <- test_rows$D[i]
    kval <- test_rows$k_test[i]
    Kval <- Fval * exp(kval)

    u_max <- u_max_for_tau_days(td)
    n_u <- ceiling(u_max / DU_TARGET)
    u_grid <- seq(0, u_max, length.out = n_u + 1L)
    cf_vec <- sapply(u_grid, function(u) black_cf_log_forward(u - 0.5i, Tval, sigma_test))

    p_black <- black_call_forward(Fval, Kval, Tval, sigma_test, Dval)
    p_lewis <- lewis_call_from_cf_generic(kval, Tval, cf_vec, u_grid, Fval, Dval)

    tibble(
      tau_days = td,
      tau = Tval,
      k = kval,
      u_max = u_max,
      n_u = n_u,
      price_black = p_black,
      price_lewis = p_lewis,
      abs_error = abs(p_black - p_lewis)
    )
  }) %>% bind_rows()

  summary <- details %>%
    summarise(
      max_abs_error = max(abs_error, na.rm = TRUE),
      mean_abs_error = mean(abs_error, na.rm = TRUE),
      pass = max_abs_error < 1e-4
    )

  list(details = details, summary = summary)
}

# Local near-ATM slope used only inside the optional skew penalty.  The
# reported ATM-skew estimates are recomputed later with the full estimator.
local_slope_for_objective <- function(x, y, window = 0.055) {
  ok <- is.finite(x) & is.finite(y) & abs(x) <= window
  x <- x[ok]
  y <- y[ok]
  if (length(x) < 4L) return(NA_real_)
  if (sum(x < -0.002) < 1L || sum(x > 0.002) < 1L) return(NA_real_)
  w <- pmax(0, 1 - abs(x) / window)
  fit <- tryCatch(lm(y ~ x, weights = w), error = function(e) NULL)
  if (is.null(fit)) return(NA_real_)
  unname(coef(fit)["x"])
}

objective_from_fit <- function(fit_panel) {
  d <- fit_panel %>%
    filter(calib_used) %>%
    mutate(resid = model_iv - synthetic_iv) %>%
    filter(is.finite(resid), is.finite(weight_iv))

  if (nrow(d) < 0.80 * nrow(calib_panel)) return(1e7)

  iv_loss <- mean(d$weight_iv * d$resid^2)

  if (!is.finite(LAMBDA_SKEW) || LAMBDA_SKEW <= 0) return(iv_loss)

  skew_tbl <- d %>%
    group_by(tau_days) %>%
    summarise(
      synthetic_skew = local_slope_for_objective(k, synthetic_iv),
      model_skew = local_slope_for_objective(k, model_iv),
      .groups = "drop"
    ) %>%
    filter(is.finite(synthetic_skew), is.finite(model_skew)) %>%
    mutate(skew_error = model_skew - synthetic_skew)

  if (nrow(skew_tbl) < 3L) return(1e7)

  skew_loss <- mean(skew_tbl$skew_error^2)
  iv_loss + LAMBDA_SKEW * skew_loss
}

# Recalibrate rough Heston to the synthetic B&S implied-volatility panel.
# Successful recovery supports the calibration pipeline on this fixed grid.
calibrate_rough_synthetic <- function(starts) {
  cat("\nCalibrating rough Heston to synthetic prices with", length(starts), "starts...\n")
  results <- vector("list", length(starts))

  for (sidx in seq_along(starts)) {
    cat("  start", sidx, "of", length(starts), "\n")
    x0 <- pack_rough(starts[[sidx]])

    obj <- function(x) {
      par <- unpack_rough(x)
      priced <- price_rheston_panel(calib_panel, par, corrector_iters = RICCATI_CORRECTOR_ITERS)
      if (!isTRUE(priced$ok)) return(1e8)
      if (priced$clipped_total > 0L) return(1e7 + 1e5 * priced$clipped_total)
      val <- objective_from_fit(priced$panel)
      if (!is.finite(val)) return(1e8)
      val
    }

    fit <- optim(
      par = x0,
      fn = obj,
      method = "Nelder-Mead",
      control = list(
        maxit = MAXIT_ROUGH_SYN,
        reltol = 1e-5,
        trace = ifelse(OPT_TRACE, 1, 0),
        REPORT = 20
      )
    )

    par_hat <- unpack_rough(fit$par)
    priced_eval <- price_rheston_panel(eval_panel, par_hat, corrector_iters = RICCATI_CORRECTOR_ITERS)

    results[[sidx]] <- list(
      fit = fit,
      par = par_hat,
      priced_eval = priced_eval,
      ok = isTRUE(priced_eval$ok)
    )
  }

  obj_values <- sapply(results, function(x) x$fit$value)
  best_idx <- which.min(obj_values)
  list(
    model_name = "rough_heston_fixed_alpha_synthetic_recovery",
    results = results,
    best_idx = best_idx,
    best = results[[best_idx]]
  )
}

