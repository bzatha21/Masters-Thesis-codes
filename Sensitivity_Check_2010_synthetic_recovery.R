# The short-end power-law slope is estimated on the headline maturity set
# used for the empirical H decision.
fit_skew_powerlaw <- function(skew_tbl, skew_col, label, day_filter = HEADLINE_H_DAYS) {
  d <- skew_tbl %>%
    filter(tau_days %in% day_filter, is.finite(.data[[skew_col]]), abs(.data[[skew_col]]) > 0, tau > 0) %>%
    mutate(log_tau = log(tau), log_abs_skew = log(abs(.data[[skew_col]]))) %>%
    arrange(tau_days)

  if (nrow(d) < 3L) {
    return(tibble(
      series = label,
      n_maturities = nrow(d),
      maturity_days_used = paste(d$tau_days, collapse = ", "),
      intercept = NA_real_,
      beta_hat = NA_real_,
      H_hat = NA_real_,
      r_squared = NA_real_
    ))
  }

  fit <- lm(log_abs_skew ~ log_tau, data = d)
  tibble(
    series = label,
    n_maturities = nrow(d),
    maturity_days_used = paste(d$tau_days, collapse = ", "),
    intercept = unname(coef(fit)["(Intercept)"]),
    beta_hat = unname(coef(fit)["log_tau"]),
    H_hat = unname(coef(fit)["log_tau"]) + 0.5,
    r_squared = summary(fit)$r.squared
  )
}

