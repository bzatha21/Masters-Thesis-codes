# Parameters are optimized on an unconstrained scale and mapped back to
# economically admissible bounds before pricing.
logit <- function(x, lo, hi) log((x - lo) / (hi - x))
inv_logit <- function(y, lo, hi) lo + (hi - lo) / (1 + exp(-y))

bounds <- list(
  gamma = c(0.05, 5.00),
  theta = c(0.005, 0.50),
  nu = c(0.03, 1.50),
  rho = c(-0.95, -0.02),
  V0 = c(0.005, 0.50),
  H = c(0.03, 0.49)
)

clip_to_bounds <- function(x, b, eps = 1e-6) {
  pmin(pmax(x, b[1] + eps), b[2] - eps)
}

make_par <- function(gamma, theta, nu, rho, V0, alpha_fixed = NULL) {
  alpha <- if (is.null(alpha_fixed)) ALPHA_FIXED else alpha_fixed
  list(
    gamma = gamma,
    theta = theta,
    nu = nu,
    rho = rho,
    V0 = V0,
    H = alpha - 0.5,
    alpha = alpha
  )
}

pack_rough <- function(p) {
  c(
    logit(p$gamma, bounds$gamma[1], bounds$gamma[2]),
    logit(p$theta, bounds$theta[1], bounds$theta[2]),
    logit(p$nu, bounds$nu[1], bounds$nu[2]),
    logit(p$rho, bounds$rho[1], bounds$rho[2]),
    logit(p$V0, bounds$V0[1], bounds$V0[2])
  )
}

unpack_rough <- function(x) {
  make_par(
    gamma = inv_logit(x[1], bounds$gamma[1], bounds$gamma[2]),
    theta = inv_logit(x[2], bounds$theta[1], bounds$theta[2]),
    nu = inv_logit(x[3], bounds$nu[1], bounds$nu[2]),
    rho = inv_logit(x[4], bounds$rho[1], bounds$rho[2]),
    V0 = inv_logit(x[5], bounds$V0[1], bounds$V0[2]),
    alpha_fixed = truth_par$alpha
  )
}

perturb_truth <- function(gamma_mult = 1, theta_mult = 1, nu_mult = 1,
                          rho_shift = 0, V0_mult = 1) {
  make_par(
    gamma = clip_to_bounds(truth_par$gamma * gamma_mult, bounds$gamma),
    theta = clip_to_bounds(truth_par$theta * theta_mult, bounds$theta),
    nu = clip_to_bounds(truth_par$nu * nu_mult, bounds$nu),
    rho = clip_to_bounds(truth_par$rho + rho_shift, bounds$rho),
    V0 = clip_to_bounds(truth_par$V0 * V0_mult, bounds$V0),
    alpha_fixed = truth_par$alpha
  )
}

